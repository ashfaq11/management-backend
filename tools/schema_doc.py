"""Builds docs/schema.md from the LIVE database catalog (so it cannot drift from the real schema).

    PG_DSN=postgresql://... python tools/schema_doc.py [--schema spa]    # rewrites docs/schema.md
It migrates a scratch schema first, so no data and no existing schema is touched.
"""
import argparse
import os
import pathlib
import sys
import uuid

import psycopg

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
from app.migrate import migrate  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent


def describe(c, schema: str) -> dict:
    """Plain data about every table of a schema, straight from pg_catalog (no ordering surprises)."""
    cols = c.execute("""
        SELECT c.relname, a.attnum, a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull,
               pg_get_expr(d.adbin, d.adrelid), a.attidentity, a.attgenerated, col_description(c.oid, a.attnum)
        FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
        JOIN pg_attribute a ON a.attrelid=c.oid AND a.attnum>0 AND NOT a.attisdropped
        LEFT JOIN pg_attrdef d ON d.adrelid=c.oid AND d.adnum=a.attnum
        WHERE n.nspname=%s AND c.relkind='r' AND c.relname<>'schema_migrations' ORDER BY c.relname, a.attnum""", (schema,)).fetchall()
    cons = c.execute("""
        SELECT c.relname, k.conname, k.contype, pg_get_constraintdef(k.oid), obj_description(k.oid, 'pg_constraint')
        FROM pg_constraint k JOIN pg_class c ON c.oid=k.conrelid JOIN pg_namespace n ON n.oid=c.relnamespace
        WHERE n.nspname=%s AND c.relname<>'schema_migrations' ORDER BY c.relname, k.contype, k.conname""", (schema,)).fetchall()
    idx = c.execute("""
        SELECT tablename, indexname, indexdef FROM pg_indexes WHERE schemaname=%s AND tablename<>'schema_migrations' ORDER BY tablename, indexname""",
                    (schema,)).fetchall()
    tabs = c.execute("""
        SELECT c.relname, obj_description(c.oid, 'pg_class') FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
        WHERE n.nspname=%s AND c.relkind='r' AND c.relname<>'schema_migrations' ORDER BY c.relname""", (schema,)).fetchall()
    return {"cols": cols, "cons": cons, "idx": idx, "tabs": tabs}


def render(d: dict, schema: str = "spa") -> str:
    strip = lambda s: (s or "").replace(f"{schema}.", "")  # noqa: E731  (scratch schema name must not leak)
    out = ["# Database schema", "",
           "PostgreSQL, schema `spa` (`SPA_PG_SCHEMA`). Generated by `python tools/schema_doc.py` from the live catalog -",
           "do not edit by hand; change a `migrations/NNN_*.sql` file and regenerate. Raw DDL: [`sql/schema.sql`](../sql/schema.sql).",
           "", "## Relationships", "", "```mermaid", "erDiagram"]
    fks = [(t, strip(defn)) for t, _, ty, defn, _ in d["cons"] if ty == "f"]
    for t, defn in fks:
        ref = defn.split("REFERENCES ")[1].split("(")[0]
        out.append(f"  {ref} ||--o{{ {t} : has")
    out += ["```", "", "| Table | Purpose |", "|---|---|"]
    out += [f"| [`{t}`](#{t}) | {com or ''} |" for t, com in d["tabs"]]
    for t, com in d["tabs"]:
        out += ["", f"## {t}", "", com or "", "", "| Column | Type | Null | Default | Description |", "|---|---|---|---|---|"]
        for rel, _, name, typ, notnull, default, ident, gen, cdesc in d["cols"]:
            if rel != t:
                continue
            dflt = ("identity" if ident else f"generated: `{strip(default)}`" if gen else
                    f"`{strip(default)}`" if default else "")
            out.append(f"| `{name}` | {typ} | {'no' if notnull else 'yes'} | {dflt} | {(cdesc or '').replace('|', '/')} |")
        kinds = {"p": "Primary key", "u": "Unique", "f": "Foreign key", "c": "Check", "x": "Exclusion"}
        rows = [(k, n, strip(defn), cd) for rel, n, k, defn, cd in d["cons"] if rel == t]
        if rows:
            out += ["", "**Constraints**", ""]
            out += [f"- {kinds[k]} `{n}`: `{defn}`" + (f" - {cd}" if cd else "") for k, n, defn, cd in rows]
        ix = [(n, strip(defn)) for rel, n, defn in d["idx"] if rel == t and not n.endswith("_pkey")]
        if ix:
            out += ["", "**Indexes**", ""] + [f"- `{n}`: `{defn}`" for n, defn in ix]
    return "\n".join(out) + "\n"


def build(dsn: str) -> str:
    scratch = "doc_" + uuid.uuid4().hex[:10]
    migrate(dsn, scratch)
    try:
        with psycopg.connect(dsn) as c:
            return render(describe(c, scratch), scratch)
    finally:
        with psycopg.connect(dsn, autocommit=True) as c:
            c.execute(f"DROP SCHEMA {scratch} CASCADE")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--dsn", default=os.environ.get("PG_DSN"))
    a = ap.parse_args()
    if not a.dsn:
        sys.exit("set PG_DSN or pass --dsn")
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "schema.md").write_text(build(a.dsn))
    print("wrote docs/schema.md")
